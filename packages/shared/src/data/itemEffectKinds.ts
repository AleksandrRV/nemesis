import type { ItemCard } from '../types/cards.js';

export type ItemEffectKind =
  | 'WEAPON'
  | 'ENERGY_CHARGE'
  | 'GRENADE'
  | 'SMOKE_GRENADE'
  | 'EXTENDED_MAGAZINE'
  | 'RECON_DRONE'
  | 'MILITARY_STIMULANTS'
  | 'DECOY'
  | 'COMMS_KEY'
  | 'EVACUATION_KEY'
  | 'SELF_DESTRUCT_KEY'
  | 'DUCT_TAPE'
  | 'TOOLS'
  | 'FIRE_EXTINGUISHER'
  | 'CHEMICALS'
  | 'TECH_CORRIDOR_PLANS'
  | 'SPACE_SUIT'
  | 'NEMESIS_PLANS'
  | 'BANDAGES'
  | 'MEDKIT'
  | 'ALCOHOL'
  | 'CLOTHES'
  | 'ADRENALINE_INJECTION'
  | 'SYNTHETIC_FOOD'
  | 'ANTIDOTE'
  | 'TASER'
  | 'MOLOTOV'
  | 'QUEST'
  | 'UNKNOWN';

const ROOM_DECK_ITEM_ID = /^ITEM_(?:RED|YEL|GRE)_([A-Z_]+)_\d+$/;

const ROOM_DECK_EFFECT_BY_KEY: Readonly<Record<string, ItemEffectKind>> = {
  ENERGY_CHARGE: 'ENERGY_CHARGE',
  GRENADE: 'GRENADE',
  SMOKE_GRENADE: 'SMOKE_GRENADE',
  EXTENDED_MAGAZINE: 'EXTENDED_MAGAZINE',
  RECON_DRONE: 'RECON_DRONE',
  MILITARY_STIMULANTS: 'MILITARY_STIMULANTS',
  DECOY: 'DECOY',
  COMMS_KEY: 'COMMS_KEY',
  EVACUATION_KEY: 'EVACUATION_KEY',
  SELF_DESTRUCT_KEY: 'SELF_DESTRUCT_KEY',
  DUCT_TAPE: 'DUCT_TAPE',
  TOOLS: 'TOOLS',
  FIRE_EXTINGUISHER: 'FIRE_EXTINGUISHER',
  CHEMICALS: 'CHEMICALS',
  TECH_CORRIDOR_PLANS: 'TECH_CORRIDOR_PLANS',
  SPACE_SUIT: 'SPACE_SUIT',
  NEMESIS_PLANS: 'NEMESIS_PLANS',
  BANDAGES: 'BANDAGES',
  MEDKIT: 'MEDKIT',
  ALCOHOL: 'ALCOHOL',
  CLOTHES: 'CLOTHES',
  ADRENALINE: 'ADRENALINE_INJECTION',
  SYNTHETIC_FOOD: 'SYNTHETIC_FOOD',
};

const OTHER_EFFECT_BY_PREFIX: readonly (readonly [string, ItemEffectKind])[] = [
  ['CRAFTED_ANTIDOTE_', 'ANTIDOTE'],
  ['CRAFTED_TASER_', 'TASER'],
  ['CRAFTED_MOLOTOV_', 'MOLOTOV'],
  ['QUEST_', 'QUEST'],
];

export function getItemEffectKind(item: Pick<ItemCard, 'id' | 'isWeapon'>): ItemEffectKind {
  if (item.isWeapon) return 'WEAPON';
  const roomDeckKey = ROOM_DECK_ITEM_ID.exec(item.id)?.[1];
  if (roomDeckKey !== undefined) return ROOM_DECK_EFFECT_BY_KEY[roomDeckKey] ?? 'UNKNOWN';
  return OTHER_EFFECT_BY_PREFIX.find(([prefix]) => item.id.startsWith(prefix))?.[1] ?? 'UNKNOWN';
}
