/**
 * Сид партии для интерфейса.
 *
 * Сид — не скрытая информация движка, а часть записи о партии: по нему
 * воспроизводится тот же стол, его сообщают в отчёте об ошибке (аудит §4, P1-1).
 * В HUD показывается короткая форма, полное значение копируется по нажатию.
 */

/** Короткая форма сида: UUID целиком не помещается в строку HUD и не читается глазом. */
export function shortSeed(seed: string, length = 8): string {
  if (seed.length === 0) return '—';
  if (seed.length <= length) return seed;

  return seed.slice(0, length);
}
